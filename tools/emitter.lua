-- Writes normalized data as deterministic Lua: keys sorted (numbers ascending,
-- then strings), arrays in order, one row per line in the top-level tables.
local M = {}

local function isArray(t)
  local n = 0
  for _ in pairs(t) do n = n + 1 end
  for i = 1, n do
    if t[i] == nil then return false end
  end
  return true
end

local function sortedKeys(t)
  local keys = {}
  for k in pairs(t) do keys[#keys + 1] = k end
  table.sort(keys, function(a, b)
    local ta, tb = type(a), type(b)
    if ta ~= tb then return ta == "number" end
    return a < b
  end)
  return keys
end

local function key(k)
  if type(k) == "string" and k:match("^[%a_][%w_]*$") then return k end
  if type(k) == "number" then return "[" .. string.format("%d", k) .. "]" end
  return "[" .. string.format("%q", k) .. "]"
end

function M.serialize(v)
  local t = type(v)
  if t == "number" then
    if v == math.floor(v) then return string.format("%d", v) end
    return string.format("%.17g", v)
  elseif t == "string" then
    return (string.format("%q", v):gsub("\\\n", "\\n"))
  elseif t == "boolean" then
    return tostring(v)
  elseif t == "table" then
    local parts = {}
    if isArray(v) then
      for _, item in ipairs(v) do parts[#parts + 1] = M.serialize(item) end
    else
      for _, k in ipairs(sortedKeys(v)) do parts[#parts + 1] = key(k) .. "=" .. M.serialize(v[k]) end
    end
    return "{" .. table.concat(parts, ",") .. "}"
  end
  error("cannot serialize a " .. t, 0)
end

local HEADER = "-- Generated by tools/build_data.lua from All The Things. Do not edit; see docs/data-contract.md.\n"
  .. "local _, ns = ...\nns.Data = ns.Data or {}\n"

-- A file assigning one value to ns.Data[field].
function M.assignment(field, value)
  return HEADER .. "ns.Data." .. field .. " = " .. M.serialize(value) .. "\n"
end

-- A file assigning a table of rows to ns.Data[field], one row per line.
function M.file(field, rows)
  local lines = { HEADER .. "ns.Data." .. field .. " = {" }
  for _, k in ipairs(sortedKeys(rows)) do
    lines[#lines + 1] = key(k) .. "=" .. M.serialize(rows[k]) .. ","
  end
  lines[#lines + 1] = "}\n"
  return table.concat(lines, "\n")
end

return M
